"""Render evaluation metrics as Markdown (for docs/evaluation/) or JSON."""

from __future__ import annotations

import json
from datetime import UTC, datetime
from typing import Any

NA = "n/a"


def pct(value: float | None) -> str:
    return NA if value is None else f"{value * 100:.1f}%"


def num(value: float | None, digits: int = 1) -> str:
    return NA if value is None else f"{value:.{digits}f}"


def usd(value: float | None) -> str:
    return NA if value is None else f"${value:.4f}"


def secs(value: float | None) -> str:
    if value is None:
        return NA
    if value < 120:
        return f"{value:.1f} s"
    return f"{value / 60:.1f} min"


def ms(value: float | None) -> str:
    return NA if value is None else f"{value:,.0f} ms"


SUMMARY_ROWS: list[tuple[str, Any]] = [
    ("Runs (finished / still open)", lambda a: f"{a['finished']} / {a['unfinished']}"),
    ("Issue resolution rate", lambda a: f"{pct(a['resolution_rate'])} ({a['resolved']} of {a['finished']})"),
    ("Published (PR created)", lambda a: pct(a["published_rate"])),
    ("First-attempt test pass rate", lambda a: pct(a["first_attempt_pass_rate"])),
    ("Pass rate over all test runs", lambda a: pct(a["test_run_pass_rate"])),
    ("Recovery rate after test failures", lambda a: f"{pct(a['recovery_rate'])} (of {a['runs_with_test_failure']} runs with a failure)"),
    ("Mean tool calls per run", lambda a: num(a["mean_tool_calls"])),
    ("… requested by the model", lambda a: num(a["mean_tool_calls_by_model"])),
    ("… refused before reaching a server", lambda a: num(a["mean_tool_calls_rejected"])),
    ("… automatic retry attempts", lambda a: num(a["mean_tool_retries"])),
    ("Mean model calls per run", lambda a: num(a["mean_llm_calls"])),
    ("Mean tokens per run (input / output)", lambda a: f"{num(a['mean_input_tokens'], 0)} / {num(a['mean_output_tokens'], 0)}"),
    ("Mean completion time (wall clock)", lambda a: secs(a["mean_wall_seconds"])),
    ("Median completion time (wall clock)", lambda a: secs(a["median_wall_seconds"])),
    ("Mean agent working time", lambda a: secs(a["mean_agent_seconds"])),
    ("Mean time waiting for a reviewer", lambda a: secs(a["mean_human_wait_seconds"])),
    ("Unplanned file edits", lambda a: NA if a["unplanned_edits"] is None else f"{a['unplanned_edits']} ({pct(a['unplanned_edit_rate'])} of edited files)"),
    ("Reverted file edits", lambda a: f"{a['reverted_edits']} ({pct(a['reverted_edit_rate'])} of edited files)"),
    ("Total cost", lambda a: usd(a["total_cost_usd"])),
    ("Mean cost per run", lambda a: usd(a["mean_cost_per_run_usd"])),
    ("Cost per resolved task", lambda a: usd(a["cost_per_resolved_task_usd"])),
]


def render_markdown(summary: dict[str, Any], rows: list[dict[str, Any]], *, source: str, selection: str, generated_at: datetime | None = None) -> str:
    when = (generated_at or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Evaluation results",
        "",
        f"Generated by `scripts/evaluate.py` at {when} from `{source}`.",
        f"Selection: {selection}. Metric definitions: [docs/EVALUATION.md](../EVALUATION.md).",
        "Every number below comes from recorded runs; n/a means the records do not allow computing it.",
        "",
    ]
    if not rows:
        out += ["No runs matched the selection, so nothing was measured.", ""]
        return "\n".join(out)

    groups = [("All runs", summary["overall"])] + ([(f"`{m}`", a) for m, a in summary["by_model"].items()] if len(summary["by_model"]) > 1 else [])
    out += ["## Summary", "", "| Metric | " + " | ".join(name for name, _ in groups) + " |", "|---" * (len(groups) + 1) + "|"]
    for label, fn in SUMMARY_ROWS:
        out.append(f"| {label} | " + " | ".join(fn(agg) for _, agg in groups) + " |")
    statuses = ", ".join(f"{s}: {n}" for s, n in summary["overall"]["status_counts"].items())
    out += ["", f"Run statuses: {statuses}.", ""]

    overall = summary["overall"]
    for title, key in (("Model call latency by purpose", "llm_latency_ms"), ("Tool call duration by tool", "tool_duration_ms"), ("Workflow step duration", "step_duration_ms")):
        dist = overall[key]
        out += [f"## {title}", ""]
        if not dist:
            out += ["No data.", ""]
            continue
        out += ["| Name | Calls | p50 | p95 | Max |", "|---|---|---|---|---|"]
        out += [f"| `{name}` | {d['n']} | {ms(d['p50'])} | {ms(d['p95'])} | {ms(d['max'])} |" for name, d in dist.items()]
        out.append("")

    out += [
        "## Runs",
        "",
        "| Run | Issue | Model | Status | Resolved | Test runs (passed) | Tool calls | Model calls | Cost | Wall clock | Agent time | Files edited | Unplanned | Reverted |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        unplanned = NA if r["unplanned_edits"] is None else str(len(r["unplanned_edits"]))
        status = f"{r['status']} ({r['failure_code']})" if r["failure_code"] else r["status"]
        out.append(
            f"| `{r['run_id']}` | #{r['issue']} | `{r['model']}` | {status} | "
            f"{'yes' if r['resolved'] else 'no'} | {r['test_runs']} ({r['test_runs_passed']}) | {r['tool_calls']} | {r['llm_calls']} | {usd(r['cost_usd'])} | "
            f"{secs(r['wall_seconds'])} | {secs(r['agent_seconds'])} | {len(r['files_edited'])} | {unplanned} | {len(r['reverted_edits'])} |"
        )
    out.append("")
    return "\n".join(out)


def render_json(summary: dict[str, Any], rows: list[dict[str, Any]], *, source: str, selection: str) -> str:
    return json.dumps({"source": source, "selection": selection, "summary": summary, "runs": rows}, indent=2, default=str)
