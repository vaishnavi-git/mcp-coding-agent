"""Run today's summary check again on pull request drafts from recorded runs.

For trying a change to the check on real cases without running the whole agent. For each run it
takes the recorded issue, approved plan, final diff and test runs, and the draft as the model first
wrote it (kept in the run's summary_check record when the check corrected it, or read back from
the pull request text when it didn't), and runs the current check on them with the run's own
model. Nothing is written to the run. Each run costs one model call, about $0.02.

Usage:
  python scripts/replay_summary_check.py RUN_ID [RUN_ID ...]
  python scripts/replay_summary_check.py RUN_ID --out docs/evaluation/summary-check-replay.md
"""

from __future__ import annotations

import argparse
import asyncio
import dataclasses
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.agents.coding_agent import check_publication  # noqa: E402
from app.agents.runner import AgentRunner  # noqa: E402
from app.config import Settings  # noqa: E402
from app.llm.anthropic_provider import AnthropicProvider  # noqa: E402
from app.reliability.budget import PriceBook  # noqa: E402


def first_draft(publication: dict[str, Any]) -> dict[str, Any]:
    """The draft before the check: kept when the check corrected it, else read back from the PR text."""
    check = publication.get("summary_check") or {}
    if check.get("original"):
        return dict(check["original"])
    body = publication.get("pr_body") or ""
    summary = body.split("## Summary", 1)[-1].split("## Changes", 1)[0].strip()
    risks_text = body.split("## Risks", 1)[-1].split("\nFixes #", 1)[0] if "## Risks" in body else ""
    risks = [line[2:].strip() for line in risks_text.splitlines() if line.startswith("- ") and line.strip() != "- None identified."]
    message = re.sub(r"\n\nRefs #\d+$", "", publication.get("commit_message") or "")
    return {"pr_title": publication.get("pr_title"), "commit_message": message, "summary": summary, "risks": risks}


def describe(check: dict[str, Any]) -> list[str]:
    lines = [f"- status: **{check.get('status')}**"]
    for p in check.get("problems") or []:
        lines.append(f"  - `{p['field']}`: {p['claim']} → {p['correction']}")
    if check.get("message"):
        lines.append(f"  - {check['message']}")
    return lines


async def replay(settings: Settings, run_id: str, prices: PriceBook) -> tuple[list[str], float | None]:
    runner = AgentRunner(settings)
    view = await runner.view(run_id)
    run, state = view["run"], view["state"]
    publication = state.get("publication_draft") or {}
    if not publication:
        return [f"## `{run_id}`", "", "No pull request draft was recorded for this run.", ""], 0.0
    model = (run.get("setup") or {}).get("model") or run.get("model")
    calls: list[dict[str, Any]] = []
    provider = AnthropicProvider.from_settings(dataclasses.replace(settings, anthropic_model=model, anthropic_model_by_step={}), metrics_sink=calls.append)
    draft = first_draft(publication)
    _, check = await check_publication(provider, state, draft)
    cost = sum(prices.cost_of(c) or 0.0 for c in calls if not c.get("error"))
    out = [f"## `{run_id}` (issue #{run['issue_number']}, `{model}`)", "", "The draft that was checked:", "", "```json", json.dumps(draft, indent=2), "```", ""]
    out += ["When the run happened:", *describe(publication.get("summary_check") or {"status": "not checked"}), ""]
    out += ["Replayed with the current check:", *describe(check), f"- cost: ${cost:.4f}", ""]
    return out, cost


async def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("run_ids", nargs="+", help="recorded run ids")
    parser.add_argument("--out", type=Path, help="write the Markdown here instead of stdout")
    parser.add_argument("--env-file", type=Path, help="settings file (default: .env in the project)")
    args = parser.parse_args(argv)
    settings = Settings.from_env(args.env_file)
    prices = PriceBook(settings.anthropic_model, settings.model_prices_file, settings.price_overrides)
    when = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    text = [
        "# Summary check replay",
        "",
        f"Generated by `scripts/replay_summary_check.py` at {when}: the current summary check, run again on drafts",
        "recorded in earlier runs, with each run's own model. One model call per run; nothing was written to the runs.",
        "",
    ]
    total = 0.0
    for run_id in args.run_ids:
        lines, cost = await replay(settings, run_id, prices)
        text += lines
        total += cost or 0.0
    text.append(f"Total cost of the replay: ${total:.4f}.")
    output = "\n".join(text) + "\n"
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output)
        print(f"Wrote {args.out} (${total:.4f}).", file=sys.stderr)
    else:
        print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
